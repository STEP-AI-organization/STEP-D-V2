/**
 * 분석이 끝난 회차에 남길 한 줄(`episode.pipeline.note`).
 *
 * ## 왜 따로 뗐나
 *
 * 이 한 줄이 운영자가 보는 **유일한 분석 결과 요약**이다. 그런데 예전엔 `wrote`(이번 실행이
 * 새로 올린 추천 수) 하나로만 갈라서, **재분석이 멀쩡한 회차를 "추천 없음" 으로 바꿔 놓았다.**
 *
 * 사람이 추천을 다 채택한 뒤 같은 미디어를 다시 분석하면 `writeRecommendationsFromShorts` 의
 * `overlapsKept` 가 새 제안을 전부 걸러낸다(이미 처리한 구간을 다시 들이밀지 않으려는 의도된
 * 동작이다). 그 결과 `wrote = 0` 이 되는데, 그건 "추천이 없다" 가 아니라 **"새로 제안할 게
 * 없다"** 다. 두 상태는 운영자가 할 일이 정반대다:
 *
 *   추천 없음        → 이 회차는 쓸 게 안 나왔다. 다른 회차를 보거나 원본을 의심한다.
 *   새 추천 없음     → 이미 다 뽑아 썼다. **할 일이 없다는 뜻이고, 정상이다.**
 *
 * 실제 사례(2026-09-16 발견) — ENA 나미브 18회차: 09-10 분석에서 3건이 나와 전부 채택됐고,
 * 09-15 cast 레인 스모크가 같은 master 를 다시 분석하면서 문구가 `분석 완료 · 추천 없음` 으로
 * 덮였다. 데이터는 멀쩡했는데 운영자에게는 분석이 실패한 것처럼 보였다.
 *
 * `content-pipeline.ts` 안에 삼항 연산자로 두면 테스트가 안 붙는다(그 파일은 DB·워커 의존이
 * 딸려 와 테스트가 import 하지 못하고 소스 스캔으로만 다룬다). 그래서 의존 없는 여기로 뺐다.
 *
 * ⚠️ 문구를 바꿀 때 **"크레딧"·"충전"** 을 넣지 말 것 — `automation.ts` 의
 * `episodeAnalysisState` 가 그 두 낱말을 note 에서 찾아 "크레딧 부족으로 막힘" 으로 판정한다.
 */
export function analysisNote(wrote: number, kept: number): string {
  if (wrote > 0) return `AI 쇼츠 추천 ${wrote}건`;
  if (kept > 0) return `분석 완료 · 새 추천 없음 (기존 ${kept}건 처리됨)`;
  return "분석 완료 · 추천 없음";
}
