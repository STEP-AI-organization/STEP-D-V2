/**
 * 오버레이 말투 참조 — **실제로 터진 제목만 골라 담는다** (2026-09-03).
 *
 * ## 왜 이 필터가 있나
 *
 * 화면 오버레이 두 줄이 "정직하다"는 피드백을 받아 프롬프트를 갈아엎으면서, 말투를 **내가
 * 지정하지 않기로** 했다. 지정하면 남발한다 — "끝에 ㄷㄷ 붙여라" 를 넣었더니 실측 8클립 중
 * 7개에 붙었고, 정작 조회수 상위 40개 실제 제목엔 **ㄷㄷ 가 한 건도 없었다.**
 *
 * 그래서 실제로 터진 제목을 보여주고 거기서 가져가게 하는데, 그러면 **참조의 질이 곧 출력의
 * 질**이 된다. 채널 제목에는 말투가 없는 것들이 잔뜩 섞여 있다(콜라보 태그·회차 표기·모음집).
 * 그게 참조에 남으면 모델이 오버레이에 회차 번호를 베낀다.
 */
import assert from "node:assert/strict";
import { describe, it } from "node:test";

import { cleanHookTitles } from "../db-pg.ts";

const t = (...titles: string[]) => cleanHookTitles(titles.map((title) => ({ title })));

describe("오버레이 말투 참조 — 참조로 쓸 만한 제목만", () => {
  it("해시태그를 뗀다 — 남으면 오버레이에 `#shorts` 가 그대로 나간다", () => {
    assert.deepEqual(t("동료 태움질하던 간호사의 최후 #닥터섬보이"), ["동료 태움질하던 간호사의 최후"]);
    assert.deepEqual(t("하하를 뛰어넘는 드림이 #shorts"), ["하하를 뛰어넘는 드림이"]);
  });

  it("**회차 표기를 떨군다** — 한글 뒤 `\\b` 가 안 먹어 실제로 새어 나갔던 자리", () => {
    // JS 의 \w 는 ASCII 라 "3회" 끝에는 단어 경계가 서지 않는다. 실측으로 통과했던 문자열.
    assert.deepEqual(t("혓바닥 자유분방한 놈들에게 필요한 응징 | 3회"), []);
    assert.deepEqual(t("친부모가 왜그래 ㅜㅜ 8회"), []);
    assert.deepEqual(t("궁금하다 이 남자의 연봉 EP.260"), []);
    // 다만 "회" 가 낱말의 일부인 건 살린다 — 과하게 자르면 참조가 말라붙는다.
    assert.deepEqual(t("사회생활 10년차가 말하는 진짜 현실"), ["사회생활 10년차가 말하는 진짜 현실"]);
  });

  it("모음집·예고·다시보기는 말투가 아니다", () => {
    assert.deepEqual(t("나도 이제 1인분은 한다 하하의 솔킬모음.zip"), []);
    assert.deepEqual(t("다음주 예고 이거 실화냐"), []);
    assert.deepEqual(t("놓치면 후회하는 하이라이트 장면들"), []);
  });

  it("너무 짧은 건 콜라보 태그다 — 말투가 없다", () => {
    assert.deepEqual(t("하하X아이브", "하하X송민호"), []);
  });

  it("한글이 없으면 말투 참조가 못 된다", () => {
    assert.deepEqual(t("WELCOME TO THE FIFA ONLINE WORLD"), []);
  });

  it("같은 제목은 한 번만 — 공백만 다른 것도 같은 것으로 본다", () => {
    assert.deepEqual(
      t("유느님한테 팩트로 맞고 있는 하하", "유느님한테  팩트로 맞고 있는 하하"),
      ["유느님한테 팩트로 맞고 있는 하하"],
    );
  });

  it("**진짜 후킹 제목은 살린다** — 필터가 과하면 참조가 비어 폴백으로 떨어진다", () => {
    const kept = t(
      "동료 태움질하던 간호사의 최후",
      "하하가 손절(?)할 뻔한 양상국 미친(P) 드립 ㅋㅋㅋㅋㅋㅋㅋㅋ",
      "3글자면 충분한 부산식 맛표현 ㅋㅋㅋㅋㅋㅋㅋㅋㅋ",
      "[사회실험] 잘생겼지만 인기없는 연예인을 만난다면?",
    );
    assert.equal(kept.length, 4, `실제 상위 제목이 걸러졌다: ${JSON.stringify(kept)}`);
  });

  it("limit 을 넘겨 담지 않는다", () => {
    const many = Array.from({ length: 50 }, (_, i) => ({ title: `실제로 터진 제목 번호 ${i} 입니다` }));
    assert.equal(cleanHookTitles(many, 15).length, 15);
  });
});
